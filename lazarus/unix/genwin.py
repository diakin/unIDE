#!/usr/bin/env python3
# Генератор модулей windows/messages для сборки unIDE под Linux.
# Берёт объявления WinAPI из исходников FPC RTL (rtl/win/wininc) и
# заменяет external 'kernel32' ... на external name 'unidewin_<имя>':
# компоновщик сам называет вызовы, которые программа использует, и только
# их реализует WinImpl.pas (через LCLIntf или как заглушку).
# Запуск: python3 genwin.py <путь к fpcsrc> (результат - рядом со скриптом)
import os, re, sys
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fpcsrc/3.2.2'
inc = os.path.join(src, 'rtl', 'win', 'wininc')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'wininc')
os.makedirs(out, exist_ok=True)

ext = re.compile(r"external\s+(?:'[^']*'|[A-Za-z_][A-Za-z0-9_]*)(?:\s+name\s+'([^']*)')?(?:\s+index\s+\d+)?\s*;", re.I)
hdr = re.compile(r"(function|procedure)\s+([A-Za-z_][A-Za-z0-9_]*)", re.I)

def fix_externals(text):
    res = []
    pos = 0
    for m in ext.finditer(text):
        name = m.group(1)
        if not name:
            # имя функции - последнее объявление перед external
            heads = list(hdr.finditer(text, 0, m.start()))
            name = heads[-1].group(2)
        res.append(text[pos:m.start()])
        res.append("external name 'unidewin_%s';" % name)
        pos = m.end()
    res.append(text[pos:])
    return ''.join(res)

TYPSHRD = """
  // Linux: TRect/TPoint/TSize from unit Types, shared with LCL
  TSmallPoint = Types.TSmallPoint;
  PSmallPoint = ^TSmallPoint;
  TSize = Types.TSize;
  PSize = Types.PSize;
  TPoint = Types.TPoint;
  PPoint = Types.PPoint;
  TRect = Types.TRect;
  PRect = Types.PRect;
"""

for fn in ['base.inc', 'errors.inc', 'defines.inc', 'struct.inc', 'messages.inc',
           'ascfun.inc', 'unifun.inc', 'ascdef.inc', 'unidef.inc', 'func.inc', 'redef.inc']:
    text = open(os.path.join(inc, fn), encoding='latin-1').read()
    if fn == 'base.inc':
        # System.THandle под Linux - 32 бита (дескриптор файла), а у LCL
        # дескрипторы окон и GDI - указатели: PtrUInt, как LCLType.THandle
        text = text.replace('HANDLE = System.THandle;', 'HANDLE = PtrUInt;')
    if fn == 'struct.inc':
        text = re.sub(r"\{\$I typshrdh\.inc\}", TYPSHRD, text, flags=re.I)
        text = re.sub(r"\{\$I typshrd\.inc\}", "", text, flags=re.I)
    if fn == 'redef.inc':
        # Linux x86_64: запись до 8 байт в const идёт по значению, а функции
        # прослойки ждут указатель (как Windows) - constref передаёт адрес
        text = re.sub(r"\bconst(\s+\w+\s*:\s*T\w+)", r"constref\1", text, flags=re.I)
    text = fix_externals(text)
    open(os.path.join(out, fn), 'w', encoding='latin-1', newline='\r\n').write(
        '{ Generated by genwin.py from FPC RTL (LGPL with static linking exception) }\n' + text)
print('ok', out)

# Модули из packages/winunits-base: те же замены external
units = os.path.join(src, 'packages', 'winunits-base', 'src')
here = os.path.dirname(os.path.abspath(__file__))
for fn in sys.argv[2:] if len(sys.argv) > 2 else ['richedit.pp', 'commctrl.pp', 'shellapi.pp', 'activex.pp', 'wininet.pp']:
    text = open(os.path.join(units, fn), encoding='latin-1').read()
    text = fix_externals(text)
    # Модуль ждёт win32/win64 - под Linux их нет
    text = re.sub(r"^(unit\s+\w+\s*;)", r"\1\n{$ifdef unix}{$ifdef cpu64}{$define win64}{$else}{$define win32}{$endif}{$endif}",
                  text, count=1, flags=re.I | re.M)
    open(os.path.join(here, fn.replace('.pp', '.pas')), 'w', encoding='latin-1', newline='\r\n').write(
        '{ Generated by genwin.py from FPC packages/winunits-base (LGPL with static linking exception) }\n' + text)
