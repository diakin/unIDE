#!/usr/bin/env python3
# Заготовки WinImpl для сборки под Linux: по списку символов unidewin_*,
# которых не хватило компоновщику (undefined reference), пишет
# winimpl_auto.inc - заглушку на каждую функцию (ноль / пустая процедура).
# Функции, уже написанные в winimpl.pas руками, пропускаются.
# Запуск: python3 genimpl.py <undef.txt> <папки исходников через :>
import os, re, sys, glob

undef = [l.strip() for l in open(sys.argv[1]) if l.strip().startswith('unidewin_')]
srcdirs = sys.argv[2].split(':')
here = os.path.dirname(os.path.abspath(__file__))

texts = []
for d in srcdirs + [here, os.path.join(here, 'wininc')]:
    for f in sorted(glob.glob(os.path.join(d, '*.pas')) + glob.glob(os.path.join(d, '*.inc'))):
        if os.path.basename(f).lower().startswith('winimpl'):
            continue
        texts.append(open(f, encoding='latin-1').read())
big = '\n'.join(texts)

manual = set(m.group(1) for m in re.finditer(r"public name 'unidewin_(\w+)'",
             open(os.path.join(here, 'winimpl.pas'), encoding='cp1251').read()))


def header_for(sym):
    pos = big.find("name '%s'" % sym)
    if pos < 0:
        return None
    chunk = big[max(0, pos - 3000):pos]
    heads = list(re.finditer(r'\b(?:function|procedure)\s+\w+', chunk, re.I))
    if not heads:
        return None
    decl = chunk[heads[-1].start():]
    decl = re.sub(r'\{[^}]*\}|//[^\n]*', ' ', decl)
    depth = 0
    for idx, ch in enumerate(decl):
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        elif ch == ';' and depth == 0:
            return re.sub(r'\s+', ' ', decl[:idx + 1])
    return None


# Типы, объявленные в модулях unIDE (не видны отсюда): у var/const -
# параметр без типа (та же передача по ссылке), иначе - замена
OWN_TYPES = {'HCRYPTPROV': 'PtrUInt', 'HCRYPTHASH': 'PtrUInt', 'PFtpDataBlob': 'Pointer'}
OWN_RECORDS = {'TFarChooseColor', 'TFarWin32FindDataW', 'TFtpFindData', 'TFarOpenFileName',
               'TTabSize', 'TShellFileOpW', 'TDbgDebugEvent', 'TDbgContext'}


def fix_params(params):
    groups = [g.strip() for g in params.split(';')] if params.strip() else []
    res = []
    for grp in groups:
        gm = re.match(r'((?:var|const|out)\s+)?([^:]+):\s*([\w.]+)$', grp, re.I)
        if gm and gm.group(3) in OWN_RECORDS and gm.group(1):
            res.append(gm.group(1) + gm.group(2).strip())
        elif gm and gm.group(3) in OWN_TYPES:
            res.append((gm.group(1) or '') + gm.group(2).strip() + ': ' + OWN_TYPES[gm.group(3)])
        else:
            res.append(grp)
    return '; '.join(res)


out = []
missing = []
count = 0
for sym in undef:
    name = sym[len('unidewin_'):]
    if name in manual:
        continue
    head = header_for(sym)
    hm = head and re.match(r"(function|procedure)\s+(\w+)\s*(?:\((.*)\))?\s*(?::\s*([\w.]+))?\s*;$", head, re.I)
    if not hm:
        missing.append(name)
        continue
    kind, params, rtype = hm.group(1).lower(), hm.group(3) or '', hm.group(4)
    params = fix_params(params)
    out.append('%s Impl_%s%s%s; stdcall; public name \'%s\';' % (
        kind, name, '(' + params + ')' if params else '', ': ' + rtype if rtype else '', sym))
    out.append('begin')
    if rtype:
        out.append('  Result := Default(%s);' % rtype)
    out.append('end;')
    out.append('')
    count += 1
open(os.path.join(here, 'winimpl_auto.inc'), 'w', encoding='utf-8', newline='\r\n').write(
    '// Generated by genimpl.py: stubs for WinAPI calls used by unIDE under Linux\n\n' + '\n'.join(out))
print('stubs', count, 'missing', missing)
